export function inside(p: Point, poly: Polygon): boolean {
  let hit = false;
  for (let i=0,j=poly.length-1;i<poly.length;j=i++) {
    const a=poly[i], b=poly[j];
    if ((a.y>p.y)!==(b.y>p.y) && p.x<(b.x-a.x)*(p.y-a.y)/(b.y-a.y)+a.x) hit=!hit;
  }
  return hit;
}
export function walkable(p: Point): boolean {
  for (let i=0;i<8;i++) {
    const a=i*Math.PI/4, q={x:p.x+Math.cos(a)*radius,y:p.y+Math.sin(a)*radius};
    if (!floors.some(poly=>inside(q,poly)) || obstacles.some(poly=>inside(q,poly))) return false;
  }
  return true;
}
export function move(p: Point, dx: number, dy: number): Point {
  const steps=Math.max(1,Math.ceil(Math.hypot(dx,dy)/(radius/2)));
  let q={...p};
  for(let i=0;i<steps;i++) {
    const x={x:q.x+dx/steps,y:q.y}; if(walkable(x)) q=x;
    const y={x:q.x,y:q.y+dy/steps}; if(walkable(y)) q=y;
  }
  return q;
}
